"""Binary heaps, across two Algorithms courses.

Four modes, four lessons:

    ops        Priority Queues and Binary Heaps          (data-structures)
    build      Building a Heap in Linear Time            (data-structures)
    heapsort   Heapsort                                  (sorting-and-selection)
    kway       k-Way Merging and Sorting in Practice     (sorting-and-selection)

The engine is `algo_core.HEAP_JS` as it ships -- `heapInsert`, `heapExtract`,
`floydBuild`, `insertBuild`, `buildSumExact`, `heapsortRun`, `kwayMerge`,
`pairwiseMerge` -- with `algebra_core.RATIONAL_JS` underneath it, because
Floyd's sum is a sum of integers and the panel divides it by `n`: that ratio is
a fraction and is printed as one.

THREE THINGS ARE REUSED FROM `algorithms.ALGO_JS` EXACTLY AS THEY SHIP, and all
three are inputs or baselines rather than machinery:

  * `mergeSort` returns a comparison TOTAL, which is precisely what heapsort is
    measured against and all that is wanted from it;
  * `makeArray(n, 'shuffle')` is one fixed permutation generated by a
    deterministic step, so two readers at the same n see the same array and the
    same counts. It takes no seed and none is wanted here.
  * `ilog2` is the floor of the base-two logarithm, which is the bound the
    per-operation comparison counts are measured against.

Every block this kit concatenates is one the kit uses. `SERIES_JS` and
`TREEDRAW_JS` are not used by all FOUR modes, though, and the core is built once
for the kit rather than once per mode -- which is what `estimate.py` does, and
what keeps a mode from calling a function its own page turned out not to carry.
The cost of that choice is about 3 KB gzipped on the two lightest modes, against
a measured ceiling of 62 KB and a heaviest page here of 36 KB.

ONE THING IS NOT, and the design assumed it was. §4.2's `kway` row names
`ALGO_JS.insertionSort` for the hybrid cutoff arm. That function returns a
comparison total and discards the sorted array, so it cannot be the first half
of a hybrid -- the merge has to RECEIVE the sorted run. `insertionSortRun` below
is the same algorithm counted the same way, returning the output as well, and
scripts/mathcheck.js pins its comparison count to `ALGO_JS.insertionSort`'s on
the same input so the two cannot drift.

`heapsortTagged` is the other kit-local re-run, and it exists for the same kind
of reason: the misconception `heapsort` names is that a sort in the same
complexity class as merge sort must be stable, and showing otherwise needs
records with tags, which `heapsortRun` (numbers) cannot carry. It is pinned the
same way -- it must agree with `heapsortRun` on comparisons AND swaps for the
same keys, which is a much tighter constraint than agreeing on the output.
"""

